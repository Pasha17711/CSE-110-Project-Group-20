-- The leaderboard_entries table as it was first created in the Supabase dashboard
-- (checked 2026-11-20). Already applied: this file is a record, don't run it on
-- the live project.

create table leaderboard_entries (
  id bigint generated by default as identity primary key,
  player_name text,
  difficulty smallint not null,
  score integer,
  time_spent_ms integer,
  created_at timestamptz not null default now(),

  constraint difficulty_valid check (difficulty = any (array[0, 1, 2])),
  constraint name_length check (char_length(btrim(player_name)) between 1 and 20),
  constraint score_nonneg check (score >= 0),
  constraint time_nonneg check (time_spent_ms >= 0)
);

alter table leaderboard_entries enable row level security;

create policy "anon can read" on leaderboard_entries
  for select to anon using (true);
create policy "anon can insert" on leaderboard_entries
  for insert to anon with check (true);
